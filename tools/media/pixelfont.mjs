export const ADVANCE = 6
export function textWidth(text, scale) { return (text.length * ADVANCE - 1) * scale }
/** Draws text with its top-left at (x, y); `color(i)` picks the colour per character. */
export function drawText(ctx, text, x, y, scale, color) {
  ;[...text].forEach((ch, i) => {
    const g = G[ch]
    if (!g) throw new Error('no glyph for ' + JSON.stringify(ch))
    ctx.fillStyle = typeof color === 'function' ? color(i) : color
    g.forEach((row, ry) => { for (let rx = 0; rx < 5; rx++) if (row[rx] === '#') ctx.fillRect(x + (i * ADVANCE + rx) * scale, y + ry * scale, scale, scale) })
  })
}
export const GLYPHS = G
