export type PaletteKey = keyof typeof BASE_PALETTE
type Palette = { -readonly [K in PaletteKey]: K extends 'books' ? readonly string[] : string }

/** The colours in use now: the base, then the theme's overrides, then the sky of the hour. */
export const P: Palette = { ...BASE_PALETTE }

/** Puts back the base palette and applies the overrides (a theme, the sky of the hour). */
export function setPalette(...overrides: Partial<Record<PaletteKey, string | readonly string[]>>[]): void {
  Object.assign(P, BASE_PALETTE, ...overrides)
}

